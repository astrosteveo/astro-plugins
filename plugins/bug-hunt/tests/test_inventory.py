import ast
import os
import subprocess
import sys
import tempfile
import time
import unittest
from pathlib import Path
from unittest import mock

SCRIPT = Path(__file__).resolve().parents[1] / "skills" / "hunt" / "scripts" / "inventory.py"
sys.path.insert(0, str(SCRIPT.parent))
import inventory  # noqa: E402

GIT_ENV = {
    **os.environ,
    "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t", "GIT_COMMITTER_NAME": "t",
    "GIT_COMMITTER_EMAIL": "t@t", "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1",
}


def lines(n):
    return "".join(f"x = {i}\n" for i in range(n))


class InventoryTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name).resolve()

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, rel, text):
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode() if isinstance(text, str) else text)

    def git(self, *args):
        subprocess.run(["git", *args], cwd=self.root, env=GIT_ENV, check=True, capture_output=True)

    def commit(self, message="c"):
        self.git("add", ".")
        self.git("commit", "-q", "-m", message)

    def run_report(self, *paths, budget=inventory.DEFAULT_BUDGET, cwd=None):
        return inventory.report(cwd or self.root, list(paths), budget)

    def units(self, text):
        block = text.split("\nunits:\n")[1].split("\n\n")[0]
        return [row[2:].split("  ")[0] for row in block.splitlines()]

    def test_a_directory_that_fits_the_budget_is_one_unit(self):
        self.git("init", "-q")
        self.write("src/auth/login.py", lines(40))
        self.write("src/auth/session.py", lines(30))
        self.write("src/shop/cart.py", lines(50))
        self.commit()
        self.assertEqual(self.units(self.run_report(budget=100)), ["src/auth/", "src/shop/"])
        self.assertEqual(self.units(self.run_report(budget=1000)), ["src/"])

    def test_a_directory_over_the_budget_splits_into_its_subdirectories_and_own_files(self):
        self.git("init", "-q")
        self.write("game/main.py", lines(20))
        self.write("game/save/files.py", lines(60))
        self.write("game/ui/menu.py", lines(60))
        self.commit()
        self.assertEqual(
            self.units(self.run_report(budget=100)),
            ["game/save/", "game/ui/", "game/* (files directly in it)"],
        )

    def test_own_files_over_the_budget_pack_in_name_order_and_a_big_file_stands_alone(self):
        self.git("init", "-q")
        self.write("lib/a.py", lines(40))
        self.write("lib/b.py", lines(40))
        self.write("lib/big.py", lines(500))
        self.write("lib/c.py", lines(40))
        self.commit()
        text = self.run_report(budget=100)
        self.assertEqual(self.units(text), ["lib/{a.py, b.py}", "lib/big.py", "lib/c.py"])
        self.assertIn("lib/big.py  1 file, 500 lines, 1 commit (one file over the budget)", text)

    def test_vendored_generated_and_binary_files_are_left_out(self):
        self.git("init", "-q")
        self.write("app.py", lines(10))
        self.write("node_modules/dep/index.js", lines(10))
        self.write("vendor/lib.go", lines(10))
        self.write("api.pb.go", lines(10))
        self.write("package-lock.json", "{}\n")
        self.write("bundle.min.js", lines(10))
        self.write("schema.go", "// Code generated by sqlc. DO NOT EDIT.\npackage db\n")
        self.write("logo.png", b"\x89PNG\r\n\x1a\n\0\0\0")
        self.write("notes.md", "# notes\n")
        self.commit()
        text = self.run_report()
        self.assertIn("code: 1 file, 10 lines, in 1 unit", text)
        self.assertIn("not code: 2 vendored, 4 generated, 1 binary, 1 other text file", text)

    def test_tests_are_counted_apart_from_code(self):
        self.git("init", "-q")
        self.write("pkg/calc.go", lines(30))
        self.write("pkg/calc_test.go", lines(20))
        self.write("src/cart.ts", lines(30))
        self.write("src/cart.test.ts", lines(5))
        self.write("tests/test_cart.py", lines(7))
        self.write("Game.Tests/CartTests.cs", lines(9))
        self.commit()
        text = self.run_report()
        self.assertIn("code: 2 files, 60 lines", text)
        self.assertIn("tests: 4 files, 41 lines", text)
        self.assertIn("- tests/  1 file, 7 lines", text)

    def test_a_script_without_an_extension_is_code_when_it_has_a_shebang(self):
        self.git("init", "-q")
        self.write("bin/deploy", "#!/bin/sh\necho hi\n")
        self.write("LICENSE", "MIT\n")
        self.commit()
        self.assertIn("code: 1 file, 2 lines", self.run_report())

    def test_untracked_files_count_and_ignored_ones_do_not(self):
        self.git("init", "-q")
        self.write(".gitignore", "build/\n")
        self.write("app.py", lines(5))
        self.commit()
        self.write("new.py", lines(3))
        self.write("build/out.py", lines(100))
        self.assertIn("code: 2 files, 8 lines", self.run_report())

    def test_each_unit_says_how_many_recent_commits_touched_it(self):
        self.git("init", "-q")
        self.write("hot/a.py", lines(5))
        self.write("cold/b.py", lines(5))
        self.commit()
        self.write("hot/a.py", lines(6))
        self.commit()
        self.write("hot/a.py", lines(7))
        self.commit()
        text = self.run_report(budget=10)
        self.assertIn("- cold/  1 file, 5 lines, 1 commit\n", text)
        self.assertIn("- hot/  1 file, 7 lines, 3 commits", text)

    def test_paths_limit_the_listing_and_resolve_from_the_current_folder(self):
        self.git("init", "-q")
        self.write("src/auth/login.py", lines(10))
        self.write("src/shop/cart.py", lines(20))
        self.commit()
        text = self.run_report("auth", cwd=self.root / "src")
        self.assertIn("scope: src/auth", text)
        self.assertIn("code: 1 file, 10 lines", text)
        with self.assertRaises(SystemExit):
            self.run_report("nope")

    def test_a_folder_without_git_is_walked_without_hidden_or_build_folders(self):
        self.write("main.rs", lines(10))
        self.write("target/debug/build.rs", lines(10))
        self.write(".hidden/x.py", lines(10))
        self.write("node_modules/x/index.js", lines(10))
        text = self.run_report()
        self.assertIn("not a git repo", text)
        self.assertIn("code: 1 file, 10 lines", text)
        self.assertTrue(text.endswith("\n- ./  1 file, 10 lines"), text)

    def test_the_unit_list_is_cut_off_on_a_large_repo(self):
        self.git("init", "-q")
        for name in "abcde":
            self.write(f"{name}/m.py", lines(10))
        self.commit()
        with mock.patch.object(inventory, "MAX_UNITS", 3):
            text = self.run_report(budget=10)
        self.assertEqual(len(self.units(text)), 4)
        self.assertIn("and 2 more units not shown: run again with a path to list them", text)

    def test_the_cli_prints_the_report_and_refuses_a_zero_budget(self):
        self.git("init", "-q")
        self.write("app.py", lines(3))
        self.commit()
        run = subprocess.run([sys.executable, str(SCRIPT)], cwd=self.root, capture_output=True, text=True)
        self.assertEqual(run.returncode, 0, run.stderr)
        self.assertIn("code: 1 file, 3 lines", run.stdout)
        run = subprocess.run(
            [sys.executable, str(SCRIPT), "--budget", "0"], cwd=self.root, capture_output=True, text=True
        )
        self.assertEqual(run.returncode, 2)
        self.assertIn("--budget must be at least 1", run.stderr)

    def test_the_repo_root_among_other_paths_lists_the_whole_repo(self):
        # `inventory.py . src` once listed only src/, leaving the rest of the repo off the map.
        self.git("init", "-q")
        self.write("src/a.py", lines(1))
        self.write("other/b.py", lines(1))
        self.write("c.py", lines(1))
        self.commit()
        self.assertIn("code: 3 files", self.run_report(".", "src"))

    def test_a_path_outside_the_repo_is_refused_without_a_traceback(self):
        self.git("init", "-q")
        self.write("a.py", lines(1))
        self.commit()
        outside = tempfile.TemporaryDirectory()
        self.addCleanup(outside.cleanup)
        with self.assertRaises(SystemExit) as stop:
            self.run_report(outside.name)
        self.assertIn("outside the repo", str(stop.exception))

    def test_a_listing_of_one_path_names_the_unit_by_its_path(self):
        # It once labelled the only unit ./ although it held only src/.
        self.git("init", "-q")
        self.write("src/a.py", lines(1))
        self.write("b.py", lines(1))
        self.commit()
        self.assertEqual(self.units(self.run_report("src")), ["src/"])

    def test_recent_commits_count_files_with_non_ascii_names(self):
        # git log quotes such names unless told not to, so they never matched the real path.
        self.git("init", "-q")
        self.write("café/é.py", lines(1))
        self.commit()
        self.assertIn("- café/  1 file, 1 line, 1 commit", self.run_report())

    def test_a_directory_named_with_braces_or_a_star_keeps_its_test_count(self):
        # The unit's directory was once read back from its label, which these characters break.
        self.git("init", "-q")
        self.write("a{b}/m.py", lines(5))
        self.write("a{b}/tests/test_m.py", lines(2))
        self.write("x*y/n.py", lines(5))
        self.write("x*y/tests/test_n.py", lines(2))
        self.commit()
        text = self.run_report(budget=6)
        self.assertIn("- a{b}/  1 file, 5 lines, 1 test file inside", text)
        self.assertIn("- x*y/  1 file, 5 lines, 1 test file inside", text)

    def test_code_that_only_mentions_generation_is_still_code(self):
        self.git("init", "-q")
        self.write("a.py", "# this file is not auto-generated\nx = 1\n")
        self.write("b.cs", "// <auto-generated>\n//   This code was generated by a tool.\n// </auto-generated>\nclass B {}\n")
        self.write("c.py", "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# source: c.proto\nx = 1\n")
        self.commit()
        self.assertIn("code: 1 file, 2 lines", self.run_report())
        self.assertIn("2 generated", self.run_report())

    def test_files_that_are_not_code_are_not_read_to_the_end(self):
        # Their line counts were never used, and a large data file took the whole read.
        self.write("data.csv", "a,b\n" * 5000)
        self.assertEqual(inventory.classify(self.root, "data.csv"), ("other", 0))

    def test_units_split_in_time_that_grows_with_the_tree_not_its_square(self):
        # 20,000 files at a 1-line budget once took 12 s.
        code = {f"d{i // 10}/s{i % 7}/f{i}.py": 1 for i in range(20000)}
        started = time.monotonic()
        units = inventory.make_units(code, 1)
        self.assertEqual(len(units), 20000)
        self.assertLess(time.monotonic() - started, 2.0)

    def test_a_unit_holding_only_some_of_its_directory_says_so(self):
        # Listing shopgame/pricing and shopgame/shop.py labelled their unit shopgame/, as if it held
        # all of shopgame.
        self.git("init", "-q")
        self.write("shopgame/pricing/prices.py", lines(5))
        self.write("shopgame/shop.py", lines(5))
        self.write("shopgame/saves/files.py", lines(5))
        self.write("shopgame/tests/test_saves.py", lines(2))
        self.commit()
        text = self.run_report("shopgame/pricing", "shopgame/shop.py")
        self.assertEqual(self.units(text), ["shopgame/ (only the listed paths in it)"])
        self.assertNotIn("test file inside", text)
        self.assertEqual(self.units(self.run_report("shopgame")), ["shopgame/"])

    @unittest.skipUnless(hasattr(os, "mkfifo"), "needs named pipes")
    def test_a_named_pipe_in_a_folder_without_git_does_not_hang_the_listing(self):
        # Outside git the walk kept the pipe, and reading it to classify it blocked forever.
        self.write("main.py", "x = 1\n")
        os.mkfifo(str(self.root / "events.fifo"))
        run = subprocess.run(
            [sys.executable, str(SCRIPT)], cwd=self.root, capture_output=True, text=True, timeout=20
        )
        self.assertEqual(run.returncode, 0, run.stderr)
        self.assertIn("code: 1 file, 1 line", run.stdout)

    def test_the_script_parses_as_python_3_8(self):
        # The plugins' constraint is Python 3.8+ with the standard library only.
        ast.parse(SCRIPT.read_text(), feature_version=(3, 8))


if __name__ == "__main__":
    unittest.main()
